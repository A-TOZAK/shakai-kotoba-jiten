def js_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def row_to_js(index: int, row: tuple[str, ...]) -> str:
    term, reading, grade, unit, category, meaning, example, related, tags = row
    row_id = f"textbook-priority-{index:03d}"
    values = [
        row_id,
        term,
        reading,
        initial(reading),
        grade,
        unit,
        category,
        meaning,
        example,
        related,
        tags,
        SOURCE,
    ]
    rendered = []
    for value in values:
        if isinstance(value, int):
            rendered.append(str(value))
        else:
            rendered.append(js_string(value))
    return "  [" + ", ".join(rendered) + "]"


def main() -> None:
    text = TERMS_JS.read_text(encoding="utf-8")
    existing_terms = set(re.findall(r'\[\s*"[^"]+"\s*,\s*"([^"]+)"', text))
    new_rows = [row for row in ROWS if row[0] not in existing_terms]
    if not new_rows:
        print("no new rows")
        return

    rendered_rows = []
    for offset, row in enumerate(new_rows, start=301):
        rendered_rows.append(row_to_js(offset, row))

    marker = "\n];\n\nfunction generatedCounts()"
    if marker not in text:
        raise SystemExit("Could not find termRows terminator")

    insertion = ",\n" + ",\n".join(rendered_rows)
    text = text.replace(marker, insertion + marker, 1)
    TERMS_JS.write_text(text, encoding="utf-8")
    print(f"added {len(new_rows)} rows")


if __name__ == "__main__":
    main()
